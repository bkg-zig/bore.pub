#!/usr/bin/env bash
#
# start.sh - run pinokiod locally, put Basic Auth in front of it, and expose it
# through a bore tunnel. Keeps url.md and a shared tunnels/ state file current
# so the Pinokio plugin dashboard can list the live URL (bore.pub ports are
# random on every launch).
#
#   ./start.sh                     # pinokiod :42000, auth, public bore.pub URL
#   PORT=8080 ./start.sh           # different local port
#   AUTH=0 ./start.sh              # no password (NOT recommended)
#   AUTH_USER=me AUTH_PASS=secret ./start.sh
#   BORE_PORT=12345 ./start.sh     # ask for a specific public port (best effort)
#   BORE_SERVER=tunnel.example.com BORE_SECRET=xyz ./start.sh
#   NO_TUNNEL=1 ./start.sh         # local only
#   URL_PUSH=1 ./start.sh          # commit + push url.md on start/stop
#
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

PORT="${PORT:-42000}"
BORE_SERVER="${BORE_SERVER:-bore.pub}"
BORE_PORT="${BORE_PORT:-0}"
BORE_SECRET="${BORE_SECRET:-}"
NO_TUNNEL="${NO_TUNNEL:-0}"

# Basic Auth. On by default: the tunnel exposes a shell, not a brochure.
AUTH="${AUTH:-1}"
AUTH_USER="${AUTH_USER:-pinokio}"
AUTH_PASS="${AUTH_PASS:-}"
AUTH_PORT="${AUTH_PORT:-$((PORT + 1))}"
TUNNEL_PORT="$PORT"

# Where pinokiod lives.
if [[ -n "${PINOKIO_DIR:-}" ]]; then
  :
elif [[ -f "$SCRIPT_DIR/script/index.js" ]]; then
  PINOKIO_DIR="$SCRIPT_DIR"
else
  PINOKIO_DIR="$HOME/pinokiod"
fi
[[ -f "$PINOKIO_DIR/script/index.js" ]] || {
  printf '\033[31m[error]\033[0m pinokiod not found at %s - run install.sh first\n' "$PINOKIO_DIR" >&2
  exit 1
}
cd "$PINOKIO_DIR"

PINOKIO_HOME="${PINOKIO_HOME:-$HOME/.pinokio}"
export PINOKIO_HOME
mkdir -p "$PINOKIO_HOME"

LOG_DIR="${LOG_DIR:-$PINOKIO_DIR/logs}"
mkdir -p "$LOG_DIR"
APP_LOG="$LOG_DIR/pinokiod.log"
BORE_LOG="$LOG_DIR/bore.log"
CRED_FILE="$LOG_DIR/credentials.txt"
: >"$BORE_LOG"

# Shared state: the plugin dashboard reads these on every page load.
STATE_DIR="${STATE_DIR:-$PINOKIO_HOME/tunnels}"
mkdir -p "$STATE_DIR"
STATE_FILE="$STATE_DIR/pinokio.json"
URL_FILE="${URL_FILE:-$SCRIPT_DIR/url.md}"
URL_PUSH="${URL_PUSH:-0}"

BORE_PID=""
APP_PID=""
PROXY_PID=""
TAIL_PIDS=()
URL=""

log()  { printf '\033[36m[start]\033[0m %s\n' "$*"; }
fail() { printf '\033[31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

write_url_md() {
  local state="$1"
  {
    echo "# Live URL"
    echo
    echo "<!-- Auto-generated by start.sh on launch and shutdown. Do not edit by hand. -->"
    echo
    case "$state" in
      live)
        echo "## http://${URL}"
        echo
        echo "Username: \`${AUTH_USER}\` (password is printed in the terminal)"
        ;;
      closed)
        echo "## no active tunnel"
        echo
        echo "Last URL: \`http://${URL}\` (no longer valid)"
        ;;
      *)
        echo "## starting..."
        ;;
    esac
    echo
    echo "| | |"
    echo "|---|---|"
    echo "| Local | \`http://localhost:${PORT}\` |"
    echo "| Tunnel | \`bore local ${TUNNEL_PORT} --to ${BORE_SERVER}\` |"
    echo "| Auth | \`${AUTH}\`${AUTH:+ (user ${AUTH_USER})} |"
    echo "| State | \`${state}\` |"
    echo "| Updated | $(date -u +%Y-%m-%dT%H:%M:%SZ) |"
  } >"$URL_FILE"
}

write_state() {
  local state="$1"
  {
    printf '{\n'
    printf '  "name": "pinokio",\n'
    printf '  "kind": "pinokiod",\n'
    printf '  "state": "%s",\n' "$state"
    printf '  "local_port": %s,\n' "$PORT"
    printf '  "public_port": %s,\n' "${URL##*:}"
    printf '  "url": "%s",\n' "${URL:+http://$URL}"
    printf '  "auth": %s,\n' "$([[ "$AUTH" == 1 ]] && echo true || echo false)"
    printf '  "auth_user": "%s",\n' "$AUTH_USER"
    printf '  "updated": "%s"\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '}\n'
  } >"$STATE_FILE"
}

push_url_md() {
  [[ "$URL_PUSH" == 1 ]] || return 0
  local dir file
  dir="$(dirname "$URL_FILE")"
  file="$(basename "$URL_FILE")"
  git -C "$dir" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0
  git -C "$dir" add -- "$file" >/dev/null 2>&1 || return 0
  git -C "$dir" diff --cached --quiet >/dev/null 2>&1 && return 0
  git -C "$dir" -c user.name="bore.pub" -c user.email="bot@users.noreply.github.com" \
    commit -q -m "url: $1" -- "$file" >/dev/null 2>&1 || return 0
  GIT_SSH_COMMAND="ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new" \
    git -C "$dir" push -q origin HEAD >/dev/null 2>&1 \
    || log "warning: could not push url.md"
  return 0
}

cleanup() {
  local code=$?
  trap - EXIT INT TERM
  log "shutting down"
  for p in "${TAIL_PIDS[@]:-}"; do [[ -n "$p" ]] && kill "$p" 2>/dev/null || true; done
  [[ -n "$BORE_PID" ]] && kill "$BORE_PID" 2>/dev/null || true
  [[ -n "$PROXY_PID" ]] && kill "$PROXY_PID" 2>/dev/null || true
  if [[ -n "$APP_PID" ]]; then
    kill -TERM "$APP_PID" 2>/dev/null || true
    for _ in {1..30}; do kill -0 "$APP_PID" 2>/dev/null || break; sleep 0.2; done
    kill -KILL "$APP_PID" 2>/dev/null || true
  fi
  if [[ -n "$URL" ]]; then
    write_url_md closed || true
    write_state closed || true
    push_url_md "closed (last: http://${URL})" || true
  else
    rm -f "$STATE_FILE" 2>/dev/null || true
  fi
  wait 2>/dev/null || true
  exit "$code"
}
trap cleanup EXIT INT TERM

# ---- preflight -------------------------------------------------------------
command -v node >/dev/null || fail "node not found - run install.sh first"
[[ -d "$PINOKIO_DIR/node_modules" ]] || fail "node_modules missing - run install.sh first"

if curl -fsS -o /dev/null --max-time 2 "http://127.0.0.1:${PORT}/" 2>/dev/null; then
  fail "something is already listening on port ${PORT}"
fi

# ---- pinokiod --------------------------------------------------------------
log "starting pinokiod (dir ${PINOKIO_DIR}, port ${PORT})"
node script/index >>"$APP_LOG" 2>&1 &
APP_PID=$!

log "waiting for pinokiod to come up..."
ready=0
for _ in {1..180}; do
  if ! kill -0 "$APP_PID" 2>/dev/null; then
    tail -n 40 "$APP_LOG" >&2
    fail "pinokiod exited during startup (see $APP_LOG)"
  fi
  if curl -fsS -o /dev/null --max-time 2 "http://127.0.0.1:${PORT}/" 2>/dev/null; then
    ready=1
    break
  fi
  sleep 1
done
[[ "$ready" == 1 ]] || { tail -n 40 "$APP_LOG" >&2; fail "pinokiod did not become ready in time"; }

log "pinokiod ready: http://localhost:${PORT}"
tail -n 0 -F "$APP_LOG" 2>/dev/null | sed -u "s/^/    [app] /" &
TAIL_PIDS+=($!)

# ---- auth proxy ------------------------------------------------------------
if [[ "$AUTH" == 1 ]]; then
  command -v node >/dev/null || fail "node not found"
  [[ -f "$SCRIPT_DIR/auth-proxy.js" ]] || fail "auth-proxy.js missing next to start.sh"

  if [[ -z "$AUTH_PASS" ]]; then
    AUTH_PASS="$(node -e 'process.stdout.write(require("crypto").randomBytes(9).toString("base64url"))')"
  fi

  log "starting auth proxy on 127.0.0.1:${AUTH_PORT}"
  UPSTREAM_PORT="$PORT" LISTEN_PORT="$AUTH_PORT" AUTH_USER="$AUTH_USER" AUTH_PASS="$AUTH_PASS" \
    node "$SCRIPT_DIR/auth-proxy.js" >>"$LOG_DIR/auth.log" 2>&1 &
  PROXY_PID=$!

  for _ in {1..50}; do
    code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "http://127.0.0.1:${AUTH_PORT}/" || true)"
    [[ "$code" == 401 ]] && break
    kill -0 "$PROXY_PID" 2>/dev/null || fail "auth proxy exited (see $LOG_DIR/auth.log)"
    sleep 0.2
  done
  [[ "${code:-}" == 401 ]] || fail "auth proxy did not answer with 401 (see $LOG_DIR/auth.log)"

  TUNNEL_PORT="$AUTH_PORT"
  umask 077
  printf 'url  http://127.0.0.1:%s\nuser %s\npass %s\n' "$AUTH_PORT" "$AUTH_USER" "$AUTH_PASS" >"$CRED_FILE"
  chmod 600 "$CRED_FILE"
  umask 022
fi

if [[ "$NO_TUNNEL" == 1 ]]; then
  log "NO_TUNNEL=1 - skipping bore"
  if [[ "$AUTH" == 1 ]]; then
    printf '\n  Local : http://localhost:%s\n  User  : %s\n  Pass  : %s\n\n' "$AUTH_PORT" "$AUTH_USER" "$AUTH_PASS"
  fi
  wait "$APP_PID"
  exit 0
fi

# ---- bore tunnel -----------------------------------------------------------
command -v bore >/dev/null || fail "bore not found - run install.sh first"

# Canonical form: bore local <port> --to <server> [--port N] [--secret X]
BORE_ARGS=(--to "$BORE_SERVER")
[[ "$BORE_PORT" != 0 ]] && BORE_ARGS+=(--port "$BORE_PORT")
[[ -n "$BORE_SECRET" ]] && BORE_ARGS+=(--secret "$BORE_SECRET")

log "opening bore tunnel to ${BORE_SERVER} (port ${TUNNEL_PORT})"
bore local "$TUNNEL_PORT" "${BORE_ARGS[@]}" >>"$BORE_LOG" 2>&1 &
BORE_PID=$!

for _ in {1..60}; do
  URL="$(sed -e 's/\x1b\[[0-9;]*m//g' "$BORE_LOG" 2>/dev/null \
        | grep -oE 'listening at [A-Za-z0-9._-]+:[0-9]+' | tail -n 1 | awk '{print $3}' || true)"
  [[ -n "$URL" ]] && break
  kill -0 "$BORE_PID" 2>/dev/null || break
  sleep 1
done

if [[ -z "$URL" ]]; then
  sed -e 's/\x1b\[[0-9;]*m//g' "$BORE_LOG" >&2
  fail "bore tunnel did not come up (see $BORE_LOG)"
fi

write_url_md live
write_state live
push_url_md "live at http://${URL}"

printf '\n'
printf '  \033[1;32m=== PINOKIO IS LIVE ===\033[0m\n\n'
printf '  Public : \033[1mhttp://%s\033[0m\n' "$URL"
if [[ "$AUTH" == 1 ]]; then
  printf '  User   : %s\n' "$AUTH_USER"
  printf '  Pass   : \033[1m%s\033[0m\n' "$AUTH_PASS"
else
  printf '  \033[31mAuth   : DISABLED\033[0m\n'
fi
printf '\n'
printf '  Local  : http://localhost:%s\n' "$TUNNEL_PORT"
printf '  Listed in the Pinokio plugin dashboard while running.\n'
printf '  Ctrl-C to stop the tunnel and the server.\n\n'

tail -n 0 -F "$BORE_LOG" 2>/dev/null | sed -u -e 's/\x1b\[[0-9;]*m//g' -e "s/^/    [bore] /" &
TAIL_PIDS+=($!)

wait "$APP_PID"
