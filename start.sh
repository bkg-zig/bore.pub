#!/usr/bin/env bash
#
# start.sh - pinokiod behind HTTP Basic Auth, published through a bore tunnel,
# with every Pinokio app port auto-tunnelled.
#
# Everything is supervised: if pinokiod, the auth proxy, the tunnel or the app
# watcher dies, it is restarted in place. The public URL only changes if the
# bore connection itself is lost (bore.pub assigns a random port per
# connection), and when that happens url.md and the plugin dashboard are
# rewritten automatically. Left alone, the URL stays the same forever.
#
#   ./start.sh                     # user bkg, random password
#   AUTH_USER=bkg AUTH_PASS=... ./start.sh
#   AUTH=0 ./start.sh              # no password (NOT recommended)
#   AUTO_APPS=0 ./start.sh         # do not tunnel app ports
#   NO_TUNNEL=1 ./start.sh         # local only
#   BORE_SERVER=tunnel.example.com BORE_SECRET=xyz BORE_PORT=42000 ./start.sh
#   URL_PUSH=1 ./start.sh          # commit + push url.md on change
#
# Stop with ./stop.sh (or Ctrl-C). Never kill by pattern.
#
set -Eeuo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

PORT="${PORT:-42000}"
# pinokiod itself always binds 42000 (DEFAULT_PORT is hardcoded upstream), so
# a different PORT would only break the readiness check. Refuse it loudly.
if [[ "$PORT" != 42000 ]]; then
  printf '\033[33m[warn]\033[0m pinokiod always listens on 42000 - ignoring PORT=%s\n' "$PORT" >&2
  PORT=42000
fi
BORE_SERVER="${BORE_SERVER:-bore.pub}"
BORE_PORT="${BORE_PORT:-0}"
BORE_SECRET="${BORE_SECRET:-}"
NO_TUNNEL="${NO_TUNNEL:-0}"
AUTO_APPS="${AUTO_APPS:-1}"

AUTH="${AUTH:-1}"
AUTH_USER="${AUTH_USER:-bkg}"
AUTH_PASS="${AUTH_PASS:-}"
AUTH_PORT="${AUTH_PORT:-$((PORT + 1))}"
TUNNEL_PORT="$PORT"

# Where pinokiod lives.
if [[ -n "${PINOKIO_DIR:-}" ]]; then
  :
elif [[ -f "$SCRIPT_DIR/script/index.js" ]]; then
  PINOKIO_DIR="$SCRIPT_DIR"
else
  PINOKIO_DIR="$HOME/pinokiod"
fi
[[ -f "$PINOKIO_DIR/script/index.js" ]] || {
  printf '\033[31m[error]\033[0m pinokiod not found at %s - run install.sh first\n' "$PINOKIO_DIR" >&2
  exit 1
}
cd "$PINOKIO_DIR"

PINOKIO_HOME="${PINOKIO_HOME:-$HOME/.pinokio}"
export PINOKIO_HOME
mkdir -p "$PINOKIO_HOME"

# Stored credentials (chmod 600, written by install.sh). Env vars win.
AUTH_ENV="${AUTH_ENV:-$PINOKIO_HOME/auth.env}"
if [[ -f "$AUTH_ENV" ]]; then
  set -a
  # shellcheck disable=SC1090
  . "$AUTH_ENV"
  set +a
fi
AUTH_USER="${AUTH_USER:-bkg}"

LOG_DIR="${LOG_DIR:-$PINOKIO_DIR/logs}"
mkdir -p "$LOG_DIR"
APP_LOG="$LOG_DIR/pinokiod.log"
BORE_LOG="$LOG_DIR/bore.log"
AUTH_LOG="$LOG_DIR/auth.log"
AUTO_LOG="$LOG_DIR/auto-tunnel.log"
CRED_FILE="$LOG_DIR/credentials.txt"
PID_FILE="$LOG_DIR/start.pid"

STATE_DIR="${STATE_DIR:-$PINOKIO_HOME/tunnels}"
mkdir -p "$STATE_DIR"
STATE_FILE="$STATE_DIR/pinokio.json"
URL_FILE="${URL_FILE:-$SCRIPT_DIR/url.md}"
URL_PUSH="${URL_PUSH:-0}"
# Write the generated password into url.md so it can always be looked up.
# URL_PUSH refuses to run while this is on, so it cannot leak via git.
URL_SHOW_PASS="${URL_SHOW_PASS:-1}"

BORE_PID=""
APP_PID=""
PROXY_PID=""
WATCH_PID=""
TAIL_PIDS=()
URL=""
STOPPING=0

log()  { printf '\033[36m[start]\033[0m %s\n' "$*"; }
warn() { printf '\033[33m[warn]\033[0m %s\n' "$*"; }
fail() { printf '\033[31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

alive() { [[ -n "${1:-}" ]] && kill -0 "$1" 2>/dev/null; }

write_url_md() {
  local state="$1"
  {
    echo "# Live URL"
    echo
    echo "<!-- Auto-generated by start.sh on launch, reconnect and shutdown. Do not edit by hand. -->"
    echo
    case "$state" in
      live)
        echo "## http://${URL}"
        echo
        echo "| | |"
        echo "|---|---|"
        echo "| User | \`${AUTH_USER}\` |"
        if [[ "$URL_SHOW_PASS" == 1 ]]; then
          echo "| Password | \`${AUTH_PASS}\` |"
        fi
        ;;
      closed)
        echo "## no active tunnel"
        echo
        echo "Last URL: \`http://${URL}\` (no longer valid)"
        ;;
      *)
        echo "## starting..."
        ;;
    esac
    echo
    echo "| | |"
    echo "|---|---|"
    echo "| Local | \`http://localhost:${TUNNEL_PORT}\` |"
    echo "| Auth | \`${AUTH}\` (user ${AUTH_USER}) |"
    echo "| State | \`${state}\` |"
    echo "| Updated | $(date -u +%Y-%m-%dT%H:%M:%SZ) |"
  } >"$URL_FILE"
}

write_state() {
  local state="$1"
  cat >"$STATE_FILE" <<JSON
{
  "name": "pinokio",
  "kind": "pinokiod",
  "state": "$state",
  "local_port": $PORT,
  "public_port": ${URL##*:},
  "url": "${URL:+http://$URL}",
  "auth": $([[ "$AUTH" == 1 ]] && echo true || echo false),
  "auth_user": "$AUTH_USER",
  "updated": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
JSON
}

push_url_md() {
  [[ "$URL_PUSH" == 1 ]] || return 0
  if [[ "$URL_SHOW_PASS" == 1 ]]; then
    log "URL_PUSH skipped: url.md contains the password (unset URL_SHOW_PASS to push)"
    return 0
  fi
  local dir file
  dir="$(dirname "$URL_FILE")"
  file="$(basename "$URL_FILE")"
  git -C "$dir" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0
  git -C "$dir" add -- "$file" >/dev/null 2>&1 || return 0
  git -C "$dir" diff --cached --quiet >/dev/null 2>&1 && return 0
  git -C "$dir" -c user.name="bore.pub" -c user.email="bot@users.noreply.github.com" \
    commit -q -m "url: $1" -- "$file" >/dev/null 2>&1 || return 0
  GIT_SSH_COMMAND="ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new" \
    git -C "$dir" push -q origin HEAD >/dev/null 2>&1 || warn "could not push url.md"
  return 0
}

# ---- components ------------------------------------------------------------

start_pinokiod() {
  node script/index >>"$APP_LOG" 2>&1 &
  APP_PID=$!
}

wait_pinokiod() {
  local ready=0
  for _ in {1..180}; do
    if ! alive "$APP_PID"; then
      tail -n 40 "$APP_LOG" >&2
      return 1
    fi
    if curl -fsS -o /dev/null --max-time 2 "http://127.0.0.1:${PORT}/" 2>/dev/null; then
      ready=1
      break
    fi
    sleep 1
  done
  [[ "$ready" == 1 ]]
}

start_proxy() {
  UPSTREAM_PORT="$PORT" LISTEN_PORT="$AUTH_PORT" AUTH_USER="$AUTH_USER" AUTH_PASS="$AUTH_PASS" \
    node "$SCRIPT_DIR/auth-proxy.js" >>"$AUTH_LOG" 2>&1 &
  PROXY_PID=$!
}

wait_proxy() {
  local code=""
  for _ in {1..50}; do
    code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 2 "http://127.0.0.1:${AUTH_PORT}/" || true)"
    [[ "$code" == 401 ]] && return 0
    alive "$PROXY_PID" || return 1
    sleep 0.2
  done
  return 1
}

start_watcher() {
  AUTO_SCRIPT="${AUTO_SCRIPT:-$PINOKIO_DIR/auto-tunnel.sh}"
  [[ -f "$AUTO_SCRIPT" ]] || { warn "auto-tunnel.sh not found - app tunnels disabled"; return 0; }
  PINOKIOD_PID="$APP_PID" PINOKIO_HOME="$PINOKIO_HOME" \
    BORE_SERVER="$BORE_SERVER" BORE_SECRET="$BORE_SECRET" \
    SKIP_PORTS="22 53 7835 3000 3001 3002 ${PORT} ${AUTH_PORT}" \
    ALLOW_PORTS="${ALLOW_PORTS:-}" \
    STATE_DIR="$STATE_DIR" LOG="$AUTO_LOG" \
    bash "$AUTO_SCRIPT" >>"$AUTO_LOG" 2>&1 &
  WATCH_PID=$!
}

# Opens the tunnel and records the URL. Returns non-zero if it could not connect.
start_bore() {
  local args=(--to "$BORE_SERVER") found=""
  [[ "$BORE_PORT" != 0 ]] && args+=(--port "$BORE_PORT")
  [[ -n "$BORE_SECRET" ]] && args+=(--secret "$BORE_SECRET")

  : >"$BORE_LOG"
  bore local "$TUNNEL_PORT" "${args[@]}" >>"$BORE_LOG" 2>&1 &
  BORE_PID=$!

  for _ in {1..60}; do
    found="$(sed -e 's/\x1b\[[0-9;]*m//g' "$BORE_LOG" 2>/dev/null \
             | grep -oE 'listening at [A-Za-z0-9._-]+:[0-9]+' | tail -n 1 | awk '{print $3}' || true)"
    [[ -n "$found" ]] && break
    alive "$BORE_PID" || return 1
    sleep 1
  done
  [[ -n "$found" ]] || return 1

  URL="$found"
  write_url_md live
  write_state live
  push_url_md "live at http://${URL}"
  return 0
}

banner() {
  printf '\n'
  printf '  \033[1;32m=== PINOKIO IS LIVE ===\033[0m\n\n'
  printf '  URL  : \033[1mhttp://%s\033[0m\n' "$URL"
  printf '  User : %s\n' "$AUTH_USER"
  printf '  Pass : \033[1m%s\033[0m\n' "$AUTH_PASS"
  printf '\n  Local: http://localhost:%s\n' "$TUNNEL_PORT"
  printf '  App tunnels and this URL are listed in the Pinokio dashboard.\n'
  printf '  Supervised: a dropped tunnel reconnects and updates url.md.\n'
  printf '  Stop with: %s/stop.sh\n\n' "$SCRIPT_DIR"
}

# ---- shutdown --------------------------------------------------------------

cleanup() {
  local code=$?
  trap - EXIT INT TERM
  STOPPING=1
  log "shutting down"
  for p in "${TAIL_PIDS[@]:-}"; do [[ -n "$p" ]] && kill "$p" 2>/dev/null || true; done
  for p in "$WATCH_PID" "$BORE_PID" "$PROXY_PID"; do
    [[ -n "$p" ]] && kill "$p" 2>/dev/null || true
  done
  if [[ -n "$APP_PID" ]]; then
    kill -TERM "$APP_PID" 2>/dev/null || true
    for _ in {1..30}; do alive "$APP_PID" || break; sleep 0.2; done
    kill -KILL "$APP_PID" 2>/dev/null || true
  fi
  if [[ -n "$URL" ]]; then
    write_url_md closed || true
    write_state closed || true
    push_url_md "closed (last: http://${URL})" || true
  else
    rm -f "$STATE_FILE" 2>/dev/null || true
  fi
  # only remove the pidfile if it is ours (a failed start must not clobber
  # the pidfile of an instance that is already running)
  if [[ "$(cat "$PID_FILE" 2>/dev/null)" == "$$" ]]; then
    rm -f "$PID_FILE" 2>/dev/null || true
  fi
  wait 2>/dev/null || true
  exit "$code"
}
trap cleanup EXIT INT TERM

# ---- preflight -------------------------------------------------------------
command -v node >/dev/null || fail "node not found - run install.sh first"
[[ -d "$PINOKIO_DIR/node_modules" ]] || fail "node_modules missing - run install.sh first"

if curl -fsS -o /dev/null --max-time 2 "http://127.0.0.1:${PORT}/" 2>/dev/null; then
  fail "something is already listening on port ${PORT}"
fi

printf '%s\n' "$$" >"$PID_FILE"

# ---- pinokiod --------------------------------------------------------------
log "starting pinokiod (dir ${PINOKIO_DIR}, port ${PORT})"
start_pinokiod
log "waiting for pinokiod to come up..."
wait_pinokiod || { tail -n 40 "$APP_LOG" >&2; fail "pinokiod did not become ready (see $APP_LOG)"; }
log "pinokiod ready: http://localhost:${PORT}"
tail -n 0 -F "$APP_LOG" 2>/dev/null | sed -u "s/^/    [app] /" &
TAIL_PIDS+=($!)

# ---- auth proxy ------------------------------------------------------------
if [[ "$AUTH" == 1 ]]; then
  [[ -f "$SCRIPT_DIR/auth-proxy.js" ]] || fail "auth-proxy.js missing next to start.sh"

  if [[ -z "$AUTH_PASS" ]]; then
    AUTH_PASS="$(node -e 'process.stdout.write(require("crypto").randomBytes(9).toString("base64url"))')"
  fi

  log "starting auth proxy on 127.0.0.1:${AUTH_PORT}"
  start_proxy
  wait_proxy || fail "auth proxy did not answer with 401 (see $AUTH_LOG)"

  TUNNEL_PORT="$AUTH_PORT"
  umask 077
  printf 'url  http://127.0.0.1:%s\nuser %s\npass %s\n' "$AUTH_PORT" "$AUTH_USER" "$AUTH_PASS" >"$CRED_FILE"
  chmod 600 "$CRED_FILE"
  umask 022
fi

# ---- app auto-tunnel -------------------------------------------------------
if [[ "$AUTO_APPS" == 1 ]]; then
  log "starting app auto-tunnel (Pinokio app ports only)"
  start_watcher
fi

# ---- bore tunnel -----------------------------------------------------------
if [[ "$NO_TUNNEL" == 1 ]]; then
  log "NO_TUNNEL=1 - skipping bore"
  banner
else
  command -v bore >/dev/null || fail "bore not found - run install.sh first"
  log "opening bore tunnel to ${BORE_SERVER} (port ${TUNNEL_PORT})"
  if start_bore; then
    banner
  else
    warn "tunnel did not come up yet - retrying in the background"
  fi
  tail -n 0 -F "$BORE_LOG" 2>/dev/null | sed -u -e 's/\x1b\[[0-9;]*m//g' -e "s/^/    [bore] /" &
  TAIL_PIDS+=($!)
fi

# ---- supervisor ------------------------------------------------------------
# Keeps every component alive. Only a real signal stops this loop.
while [[ "$STOPPING" == 0 ]]; do
  if ! alive "$APP_PID"; then
    warn "pinokiod died - restarting"
    start_pinokiod
    wait_pinokiod || warn "pinokiod still not ready, retrying"
  fi

  if [[ "$AUTH" == 1 ]] && ! alive "$PROXY_PID"; then
    warn "auth proxy died - restarting"
    start_proxy
    wait_proxy || warn "auth proxy still not ready, retrying"
  fi

  if [[ "$AUTO_APPS" == 1 ]] && [[ -n "$WATCH_PID" ]] && ! alive "$WATCH_PID"; then
    warn "app watcher died - restarting"
    start_watcher
  fi

  if [[ "$NO_TUNNEL" != 1 ]] && ! alive "$BORE_PID"; then
    warn "tunnel dropped - reconnecting"
    if start_bore; then
      log "tunnel restored: http://${URL}"
      banner
    else
      warn "reconnect failed - retrying in 10s"
      sleep 10
    fi
  fi

  stop_file="${STOP_FILE:-$LOG_DIR/stop}"
  if [[ -f "$stop_file" ]]; then
    log "stop requested via $stop_file"
    rm -f "$stop_file"
    exit 0
  fi

  sleep 3
done
